package com.ziggfreed.common.encounter.wave;

import java.util.ArrayList;
import java.util.List;

import javax.annotation.Nonnull;

import com.hypixel.hytale.component.Ref;
import com.hypixel.hytale.component.Store;
import com.hypixel.hytale.server.core.modules.entity.damage.DamageCause;
import com.hypixel.hytale.server.core.universe.world.World;
import com.hypixel.hytale.server.core.universe.world.storage.EntityStore;
import com.ziggfreed.common.effect.grid.EffectBodies;
import com.ziggfreed.common.effect.grid.RuntimeEffectGrid;

/**
 * The damage half of an endless run's ramp: a creature an endless wave raised carries one invisible, infinite native
 * effect whose {@code OutgoingDamage} raises every hit it deals by the ramp's percent (the engine's
 * {@code ScaleOutgoingDamageFromEntityEffects} step reads the attacker's active effects, a projectile's shooter
 * included), as {@code Zig_Wave_Damage_All_<percent>}: one shared asset per whole percent a run reaches, written the
 * first time a creature needs it ({@link RuntimeEffectGrid}). The ramp's cap bounds how many there are.
 *
 * <p>World thread only. A bucket still being written applies once it lands, back on the creature's world thread.
 */
public final class WaveDamage {

    /** Generated effect-id prefix: {@code Zig_Wave_Damage_All_<percent>}. */
    public static final String EFFECT_PREFIX = "Zig_Wave_Damage_";

    /** The one channel: every damage cause. */
    static final String CHANNEL = "All";

    /** The asset pack the generated effects load under. */
    static final String PACK_KEY = "ziggfreedcommon-wave-damage";

    private static final String EFFECT_COMMENT = "Runtime-generated by ziggfreed-common: an invisible always-on"
            + " effect on a creature an endless wave raised, carrying its wave's damage step as native outgoing"
            + " damage. One asset per whole percent, shared by every creature on that step. Tune the step in the"
            + " dungeon's Run.Endless.Ramp, never by overriding this asset.";

    private static final RuntimeEffectGrid GRID = new RuntimeEffectGrid(EFFECT_PREFIX, PACK_KEY, WaveDamage::body);

    private WaveDamage() {
    }

    /** The whole percent a damage multiplier raises hits by: 1.25 is 25; nothing below 1. */
    public static int percentOf(double multiplier) {
        return RuntimeEffectGrid.bucketFor((multiplier - 1.0) * 100.0, 0,
                (int) Math.round((WaveRamp.CEILING - 1.0) * 100.0));
    }

    /**
     * Put {@code percent} on {@code creature}: nothing for 0; a bucket still landing applies itself once it lands, on
     * {@code world}'s thread. Answers whether it is on now. Never throws.
     */
    public static boolean apply(@Nonnull Store<EntityStore> store, @Nonnull Ref<EntityStore> creature,
            int percent, @Nonnull World world) {
        if (percent <= 0 || !creature.isValid()) {
            return false;
        }
        RuntimeEffectGrid.Bucket bucket = new RuntimeEffectGrid.Bucket(CHANNEL, percent);
        Runnable again = RuntimeEffectGrid.onWorldThread(world, () -> {
            if (creature.isValid()) {
                GRID.applyInfinite(creature.getStore(), creature, bucket, null);
            }
        });
        return GRID.applyInfinite(store, creature, bucket, again) == RuntimeEffectGrid.Outcome.APPLIED;
    }

    /** One bucket's body: outgoing damage up by its percent on every loaded root damage cause. */
    @Nonnull
    private static String body(@Nonnull RuntimeEffectGrid.Bucket bucket) {
        return EffectBodies.damageModifiers(EffectBodies.OUTGOING_DAMAGE, EffectBodies.rootCauses(loadedCauses()),
                EffectBodies.PERCENT, bucket.value() / 100.0, EFFECT_COMMENT, true);
    }

    /** Every loaded damage cause; the body keys their roots, which the engine's outgoing walk widens to all. */
    @Nonnull
    private static List<String> loadedCauses() {
        try {
            return new ArrayList<>(DamageCause.getAssetMap().getAssetMap().keySet());
        } catch (Throwable t) {
            return List.of("Physical", "Projectile");
        }
    }

    /** Whether {@code effectId} is one of these effects. */
    public static boolean owns(@Nonnull String effectId) {
        return GRID.owns(effectId);
    }
}

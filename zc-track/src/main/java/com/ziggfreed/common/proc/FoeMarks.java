package com.ziggfreed.common.proc;

import java.util.List;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.atomic.AtomicInteger;

import javax.annotation.Nonnull;
import javax.annotation.Nullable;

import com.hypixel.hytale.assetstore.map.AssetMapWithIndexes;
import com.hypixel.hytale.component.ComponentAccessor;
import com.hypixel.hytale.component.Ref;
import com.hypixel.hytale.server.core.asset.type.entityeffect.config.EntityEffect;
import com.hypixel.hytale.server.core.asset.type.entityeffect.config.OverlapBehavior;
import com.hypixel.hytale.server.core.entity.effect.ActiveEntityEffect;
import com.hypixel.hytale.server.core.entity.effect.EffectControllerComponent;
import com.hypixel.hytale.server.core.universe.world.storage.EntityStore;
import com.ziggfreed.common.effect.grid.EffectBodies;
import com.ziggfreed.common.effect.grid.RuntimeEffectGrid;
import com.ziggfreed.common.factor.FactorContext;
import com.ziggfreed.common.stats.condition.Nearby;
import com.ziggfreed.common.stats.condition.ZigFoeFamilyCondition;

/**
 * What a per-foe counter's stacks put on the foe they are about ({@link CounterAsset.OnFoe}): a look by count, and a
 * weakness to named damage causes that grows with the stacks. Both go on with the holder as their owner, for
 * {@value #SHOW_SECONDS} seconds at a time, topped up while the stacks last (each holder pass, under
 * {@value #REFRESH_BELOW} seconds left), so whatever ends the stacks (a decay, a spend, a clear, the holder or the foe
 * leaving) leaves nothing on the foe for longer than that.
 *
 * <p><b>The weakness rides the engine.</b> A native effect's {@code DamageResistance} reads only its asset, so a
 * weakness of a whole percent is one shared runtime effect per counter and percent ({@value #PREFIX}{@code
 * <counter>_<percent>}, zc-effects' {@link RuntimeEffectGrid}), written the first time anyone needs it and shared
 * after, never one per foe; a percent still being written goes on a pass later. One foe carries one of a counter's
 * weaknesses at a time, the strongest: a holder whose stacks ask less leaves a stronger one standing, and the stronger
 * takes a weaker off. A boss or an elite (zc-entity's {@code Zig_Boss_Or_Elite} group) wears the look and never the
 * weakness. World thread.
 */
final class FoeMarks {

    /** How long one apply of a look or a weakness lasts on the foe. */
    static final float SHOW_SECONDS = 2.0f;

    /** A look or a weakness is topped up when it has less than this left. */
    static final float REFRESH_BELOW = 1.0f;

    /** The id prefix of every weakness effect. */
    static final String PREFIX = "Zig_Counter_Weakness_";

    /** The asset pack the weakness effects load under. */
    static final String PACK_KEY = "ziggfreedcommon-counters";

    private static final String COMMENT = "Runtime-generated by ziggfreed-common: the weakness a per-foe counter's "
            + "stacks put on the foe (its OnFoe.Weakness), a negative DamageResistance on the counter's named causes at "
            + "one whole percent, shared by every foe on that value. Tune it through the counter's file, never by "
            + "overriding this asset.";

    /** Channel = the counter's key, value = the whole percent. */
    private static final RuntimeEffectGrid GRID = new RuntimeEffectGrid(PREFIX, PACK_KEY, FoeMarks::body);

    /** The counter fold the bodies were last written for. */
    private static final AtomicInteger WRITTEN_FOR = new AtomicInteger(-1);

    private FoeMarks() {
    }

    /** What one holder shows on one foe: the look's index (-1: none) and the weakness percent (0: none). */
    static final class Shown {
        int look = -1;
        int weakness;
    }

    /**
     * Show {@code stacks} of the counter {@code def} on {@code foe} for {@code holder}: the look for that count and the
     * weakness for that many stacks, put on or topped up; a count of 0 takes what this holder shows off.
     */
    static void show(@Nonnull ComponentAccessor<EntityStore> accessor, @Nonnull Ref<EntityStore> holder,
            @Nonnull Ref<EntityStore> foe, @Nonnull CounterConfig.Def def, double stacks,
            @Nonnull FactorContext context, @Nonnull Shown shown) {
        CounterAsset.OnFoe onFoe = def.asset().onFoe();
        if (onFoe == null || !foe.isValid()) {
            return;
        }
        EffectControllerComponent controller = accessor.getComponent(foe, EffectControllerComponent.getComponentType());
        if (controller == null) {
            return;
        }
        List<String> looks = onFoe.effects();
        int look = lookFor(stacks, looks.size());
        if (shown.look >= 0 && shown.look != look && shown.look < looks.size()) {
            removeOwned(accessor, controller, foe, looks.get(shown.look), holder);
        }
        if (look >= 0) {
            topUp(accessor, controller, foe, looks.get(look), holder, shown.look != look);
        }
        shown.look = look;
        CounterAsset.Weakness weakness = onFoe.weakness();
        int percent = weakness == null || weakness.perStack() == null || weakness.causes().isEmpty()
                || ZigFoeFamilyCondition.inGroup(accessor, foe, ZigFoeFamilyCondition.BOSS_OR_ELITE_GROUP) ? 0
                : percentFor(stacks, Procs.evaluate(weakness.perStack(), context));
        if (shown.weakness > 0 && shown.weakness != percent) {
            removeOwned(accessor, controller, foe, GRID.effectId(bucket(def, shown.weakness)), holder);
        }
        shown.weakness = percent > 0 && weaken(accessor, controller, foe, def, percent, holder) ? percent : 0;
    }

    /** Take off everything {@code holder} shows of the counter on {@code foe}. */
    static void hide(@Nonnull ComponentAccessor<EntityStore> accessor, @Nonnull Ref<EntityStore> holder,
            @Nonnull Ref<EntityStore> foe, @Nonnull CounterConfig.Def def, @Nonnull Shown shown) {
        if (shown.look < 0 && shown.weakness <= 0) {
            return;
        }
        try {
            CounterAsset.OnFoe onFoe = def.asset().onFoe();
            EffectControllerComponent controller = !foe.isValid() ? null
                    : accessor.getComponent(foe, EffectControllerComponent.getComponentType());
            if (controller != null && onFoe != null) {
                List<String> looks = onFoe.effects();
                if (shown.look >= 0 && shown.look < looks.size()) {
                    removeOwned(accessor, controller, foe, looks.get(shown.look), holder);
                }
                if (shown.weakness > 0) {
                    removeOwned(accessor, controller, foe, GRID.effectId(bucket(def, shown.weakness)), holder);
                }
            }
        } catch (Throwable t) {
            Procs.failed("taking a counter's marks off a foe", t);
        }
        shown.look = -1;
        shown.weakness = 0;
    }

    /** The look to show for {@code stacks} out of {@code count} looks: -1 for none. Pure. */
    static int lookFor(double stacks, int count) {
        if (!(stacks > 0.0) || count <= 0) {
            return -1;
        }
        return Math.max(0, Math.min(count, (int) Math.ceil(stacks - 1e-9)) - 1);
    }

    /**
     * The whole percent weakness of {@code stacks} at {@code perStack} percent a stack, held to [0,
     * {@link CounterAsset.Weakness#MAX_PERCENT}]. Pure.
     */
    static int percentFor(double stacks, double perStack) {
        if (!(stacks > 0.0) || !(perStack > 0.0)) {
            return 0;
        }
        return RuntimeEffectGrid.bucketFor(Math.floor(stacks + 1e-9) * perStack, 0, CounterAsset.Weakness.MAX_PERCENT);
    }

    /**
     * Put the weakness at {@code percent} on {@code foe} (or top it up), taking a weaker one of the counter off it, and
     * leaving a stronger one standing. Answers whether this holder's weakness is on it now; false while the percent's
     * effect is still being written (the next pass tries again) or a stronger one stands.
     */
    private static boolean weaken(@Nonnull ComponentAccessor<EntityStore> accessor,
            @Nonnull EffectControllerComponent controller, @Nonnull Ref<EntityStore> foe, @Nonnull CounterConfig.Def def,
            int percent, @Nonnull Ref<EntityStore> holder) {
        rewriteIfRetuned();
        RuntimeEffectGrid.Bucket wanted = bucket(def, percent);
        CompletableFuture<Void> landing = GRID.landing(wanted);
        if (landing == null || !landing.isDone()) {
            return false;
        }
        String wantedId = GRID.effectId(wanted);
        for (int index : controller.getActiveEffects().keySet().toIntArray()) {
            EntityEffect effect = EntityEffect.getAssetMap().getAsset(index);
            String id = effect == null ? null : effect.getId();
            if (id == null || id.equalsIgnoreCase(wantedId) || !def.key().equals(GRID.channelOf(id))) {
                continue;
            }
            if (valueOf(id) > percent) {
                return false;
            }
            controller.removeEffect(foe, index, accessor);
        }
        return topUp(accessor, controller, foe, wantedId, holder, false);
    }

    /**
     * Put {@code effectId} on {@code foe} for {@value #SHOW_SECONDS} seconds owned by {@code holder}, unless it has
     * {@value #REFRESH_BELOW} seconds left already and {@code force} is false. Answers whether it is on now.
     */
    private static boolean topUp(@Nonnull ComponentAccessor<EntityStore> accessor,
            @Nonnull EffectControllerComponent controller, @Nonnull Ref<EntityStore> foe, @Nonnull String effectId,
            @Nonnull Ref<EntityStore> holder, boolean force) {
        int index = EntityEffect.getAssetMap().getIndex(effectId);
        EntityEffect effect = index == AssetMapWithIndexes.NOT_FOUND ? null : EntityEffect.getAssetMap().getAsset(index);
        if (effect == null) {
            return false;
        }
        ActiveEntityEffect active = controller.getActiveEffects().get(index);
        if (!force && active != null && (active.isInfinite() || active.getRemainingDuration() >= REFRESH_BELOW)) {
            return true;
        }
        boolean added = controller.addEffect(foe, index, effect, SHOW_SECONDS, OverlapBehavior.OVERWRITE, accessor,
                holder);
        if (added) {
            EffectWatch.noteFoe(holder, foe, System.nanoTime());
        }
        return added;
    }

    /** Take {@code effectId} off {@code foe} when {@code holder} owns it there (or nobody does). */
    private static void removeOwned(@Nonnull ComponentAccessor<EntityStore> accessor,
            @Nonnull EffectControllerComponent controller, @Nonnull Ref<EntityStore> foe, @Nonnull String effectId,
            @Nonnull Ref<EntityStore> holder) {
        int index = EntityEffect.getAssetMap().getIndex(effectId);
        if (index == AssetMapWithIndexes.NOT_FOUND) {
            return;
        }
        ActiveEntityEffect active = controller.getActiveEffects().get(index);
        if (active != null && (active.getOwner() == null || Nearby.same(active.getOwner(), holder))) {
            controller.removeEffect(foe, index, accessor);
        }
    }

    /** The whole percent a weakness effect's id names; 0 when it names none. */
    static int valueOf(@Nonnull String effectId) {
        int cut = effectId.lastIndexOf('_');
        try {
            return cut < 0 ? 0 : Integer.parseInt(effectId.substring(cut + 1));
        } catch (NumberFormatException e) {
            return 0;
        }
    }

    @Nonnull
    private static RuntimeEffectGrid.Bucket bucket(@Nonnull CounterConfig.Def def, int percent) {
        return new RuntimeEffectGrid.Bucket(def.key(), percent);
    }

    /** One weakness body: a negative resistance at the percent on each of the counter's causes. */
    @Nonnull
    private static String body(@Nonnull RuntimeEffectGrid.Bucket bucket) {
        CounterConfig.Def def = CounterConfig.getInstance().live(bucket.channel());
        CounterAsset.OnFoe onFoe = def == null ? null : def.asset().onFoe();
        CounterAsset.Weakness weakness = onFoe == null ? null : onFoe.weakness();
        List<String> causes = weakness == null ? List.of() : weakness.causes();
        return EffectBodies.damageModifiers(EffectBodies.DAMAGE_RESISTANCE, causes, EffectBodies.PERCENT,
                -bucket.value() / 100.0, COMMENT, false);
    }

    /** A counter fold since the bodies were written (a retuned cause list): write every one again. */
    private static void rewriteIfRetuned() {
        int generation = CounterConfig.getInstance().generation();
        int written = WRITTEN_FOR.get();
        if (written != generation && WRITTEN_FOR.compareAndSet(written, generation) && written >= 0) {
            GRID.resynthesizeAll();
        }
    }

    /** The grid's id for a percent of {@code counterKey}, for a test. */
    @Nullable
    static String weaknessId(@Nonnull String counterKey, int percent) {
        return percent <= 0 ? null : GRID.effectId(new RuntimeEffectGrid.Bucket(counterKey, percent));
    }
}

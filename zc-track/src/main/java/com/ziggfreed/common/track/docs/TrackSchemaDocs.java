/**
 * This module's authoring reference, {@code zc-track/SCHEMA.md}: the track, curve and category files, the
 * boost files and settings, and the native {@code ZigTrack} and {@code ZigBoost} rewards, rendered from their codecs by zc-progression's {@link SchemaDocWriter}, and
 * regenerated on demand with {@code :zc-track:generateSchemaDocs} through the lane.
 */
public final class TrackSchemaDocs {

    /** The reference, in reading order: the three file types, the native reward, then the shared groups. */
    @Nonnull
    public static final SchemaDocWriter.Document DOCUMENT = new SchemaDocWriter.Document("Track Schema Reference",
            "Generated by `gradlew :zc-track:generateSchemaDocs` from the live asset codecs (`TrackSchemaDocs`, "
                    + "through zc-progression's `SchemaDocWriter`). Do not hand-edit; regenerate it after "
                    + "changing a track, curve or category codec.\n\n"
                    + "One track is one file under `Server/ZiggfreedCommon/Tracks/` (subfolders are the author's "
                    + "own grouping), one curve one file under `Server/ZiggfreedCommon/TrackCurves/`, one category "
                    + "one file under `Server/ZiggfreedCommon/TrackCategories/`, one source (what a moment pays onto "
                    + "a track) one file under `Server/ZiggfreedCommon/TrackSources/`, one world rule file (track "
                    + "rules for the worlds a pattern names) one file under "
                    + "`Server/ZiggfreedCommon/TrackWorldRules/`, and in each the FILE NAME is the id; a track id "
                    + "may not contain `@`. A file may carry `\"Parent\": \"<id>\"` to start from another one, "
                    + "every leaf inheriting on omission. The server owner retunes a track in "
                    + "`mods/ziggfreedcommon/tracks.json`, a source in `track-sources.json` and a world rule file "
                    + "in `track-world-rules.json`. A world's own gameplay config sets its track rules in its "
                    + "`Plugin` group as `ZigTrackRules` (the `TrackRules` shape), which wins over a rule file for "
                    + "that world. A `ZigTrack` reward is a native reward file under `Server/Rewards/`, which an "
                    + "encounter script's `GrantReward` pays as a Claim.\n\n"
                    + "One pick (the one shape every choice, Mastery node, trainer offer and prestige perk is) is one "
                    + "file under `Server/ZiggfreedCommon/TrackPicks/`, one option a choice may offer one file under "
                    + "`Server/ZiggfreedCommon/TrackPickOptions/`, and one deck (how a group's offers are drawn) one "
                    + "file under `Server/ZiggfreedCommon/TrackPickDecks/`. One pick generator (a family of picks "
                    + "from one template: `Base`, `IdPattern`, `ForEach` axes and a `Child` pick body, each row's "
                    + "tokens filled in; `Base` may carry tokens too) is one file under "
                    + "`Server/ZiggfreedCommon/TrackPickGenerators/`, and a pick file of a generated id replaces "
                    + "that pick. A pick with `Abstract` true is a skeleton picks inherit from, and one switched off "
                    + "switches off every pick under it. The server owner retunes a pick in "
                    + "`track-picks.json` and an option in `track-pick-options.json`. A grant (`Grants`) names its "
                    + "`Kind`: the library ships `Stat` (the `StatGrant` shape; a conditional bonus is a stat of its "
                    + "own, R757); other mods register their own kinds. A track's swap and respec prices are the "
                    + "library's one price shape (`Cost`), the "
                    + "one shops use.\n\n"
                    + "One boost (a percent more on every gain on the tracks it names) is one file under "
                    + "`Server/ZiggfreedCommon/Boosts/`, retuned in `mods/ziggfreedcommon/boosts.json`; how boosts add "
                    + "up and how many may run is the one `Server/ZiggfreedCommon/BoostSettings/Default.json` record, "
                    + "retuned in `boost-settings.json`. A boost starts from a boost item's native `ZigBoost` "
                    + "interaction (`Boost`, and optional `Percent` and `Seconds`, then a `Next` that consumes the "
                    + "item, run only when the boost started), from a `Boost` reward (`Params`: `Boost`, `Percent`, "
                    + "`Seconds`) or a native `ZigBoost` reward file when its Claim is collected, or from "
                    + "`/zigboost start`.\n\n"
                    + "Every field is optional and defaults to `null` unless its Default column reads "
                    + "*(required)*.\n\n")
            .register("TrackAsset", TrackAsset.CODEC)
            .register("TrackCurveAsset", TrackCurveAsset.CODEC)
            .register("TrackCategoryAsset", TrackCategoryAsset.CODEC)
            .register("TrackSourceAsset", TrackSourceAsset.CODEC)
            .register("TrackWorldRuleAsset", TrackWorldRuleAsset.CODEC)
            .register("TrackRules", TrackRules.CODEC)
            .register("TrackPickAsset", TrackPickAsset.CODEC)
            .register("TrackPickGeneratorAsset", TrackPickGeneratorAsset.CODEC)
            .register("PickOptionAsset", PickOptionAsset.CODEC)
            .register("PickDeckAsset", PickDeckAsset.CODEC)
            .register("StatGrant", StatGrant.CODEC)
            .register("Cost", CostAsset.CODEC)
            .register("ZigTrackReward", ZigTrackReward.CODEC)
            .register("BoostAsset", BoostAsset.CODEC)
            .register("BoostSettingsAsset", BoostSettingsAsset.CODEC)
            .register("ZigBoostReward", ZigBoostReward.CODEC)
            .register("When", When.CODEC)
            .register("SourceRow", SourceRow.CODEC)
            .register("Where", WorldSelector.CODEC)
            .register("Diminish", DiminishSpec.CODEC)
            .register("ContentText", ContentTextAsset.CODEC)
            .register("RewardEntry", RewardEntryAsset.CODEC)
            .register("Requires", GateSpec.CODEC)
            .register("GateClause", GateClause.CODEC)
            .register("FactorCondition", FactorCondition.CODEC);

    private TrackSchemaDocs() {
    }

    /** Gradle entry point: {@code args[0]} is the output file ({@code zc-track/SCHEMA.md}). */
    public static void main(String[] args) {
        DOCUMENT.writeFromTask(args, "TrackSchemaDocs");
    }
}
